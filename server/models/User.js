const mongoose = require('mongoose');

const userSchema = new mongoose.Schema({
  fullName: { type: String, required: true },
  email: { type: String, required: true, unique: true, lowercase: true },
  passwordHash: { type: String, required: true },
  authTokenVersion: { type: Number, default: 0 },
  isActive: { type: Boolean, default: true, index: true },
  avatarData: { type: String, default: '' },
  phone: { type: String, default: '' },
  location: { type: String, default: '' },
  qualifications: { type: String, default: '' },
  professionalSummary: { type: String, default: '' },
  specializations: [{ type: String, trim: true }],
  experienceYears: { type: Number, min: 0, max: 70, default: null },
  skills: [{ type: String, trim: true }],
  certifications: [{ type: String, trim: true }],
  employmentHistory: [{ type: String, trim: true }],
  preferredLocations: [{ type: String, trim: true }],
  preferredEmploymentTypes: [{ type: String, enum: ['Full Time', 'Part Time', 'Contract', 'Temporary', 'Internship', 'Externship', 'Locum', 'Relief'] }],
  salaryExpectationMin: { type: Number, min: 0, default: null },
  salaryExpectationMax: { type: Number, min: 0, default: null },
  salaryExpectationCurrency: { type: String, default: 'INR', uppercase: true },
  availability: { type: String, default: '' },
  profileVisibility: { type: String, enum: ['employers', 'private'], default: 'employers' },
  isVerified: { type: Boolean, default: false },
  isMentor: { type: Boolean, default: false },
  mentorshipTopics: [{ type: String, trim: true, maxlength: 80 }],
  mentorshipAvailability: { type: String, default: '', maxlength: 500 },
  mentorshipMethods: [{ type: String, trim: true, maxlength: 40 }],
  resumeBuilder: {
    template: { type: String, enum: ['classic', 'modern', 'compact'], default: 'modern' },
    summary: { type: String, default: '', maxlength: 2000 },
    qualifications: { type: String, default: '', maxlength: 2000 },
    education: [{ institution: { type: String, maxlength: 160 }, qualification: { type: String, maxlength: 160 }, startYear: { type: String, maxlength: 10 }, endYear: { type: String, maxlength: 10 }, details: { type: String, maxlength: 1000 } }],
    experience: [{ title: { type: String, maxlength: 160 }, employer: { type: String, maxlength: 160 }, location: { type: String, maxlength: 160 }, startDate: { type: String, maxlength: 20 }, endDate: { type: String, maxlength: 20 }, details: { type: String, maxlength: 1500 } }],
    skills: [{ type: String, trim: true, maxlength: 80 }],
    certifications: [{ type: String, trim: true, maxlength: 120 }],
  },
  resumeName: { type: String, default: '' },
  resumeData: { type: String, default: '' },
  role: { type: String, default: 'Veterinarian' },
  businessDetails: {
    businessName: { type: String, default: '' },
    contactName: { type: String, default: '' },
    contactEmail: { type: String, default: '' },
    phone: { type: String, default: '' },
    website: { type: String, default: '' },
    address: { type: String, default: '' },
    registrationNumber: { type: String, default: '' },
    description: { type: String, default: '' },
    specializations: [{ type: String, trim: true }],
    facilities: [{ type: String, trim: true }],
    teamInformation: { type: String, default: '' },
    logoData: { type: String, default: '' },
  },
  resetTokenHash: { type: String, default: '' },
  resetTokenExpiresAt: { type: Date, default: null },
  createdAt: { type: Date, default: Date.now },
});

module.exports = mongoose.models.User || mongoose.model('User', userSchema);
